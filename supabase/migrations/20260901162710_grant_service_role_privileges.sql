-- service_role is used directly (not via PostgREST) by the integration test
-- suite in tests/db-client-integration -- these grants cover the tables and
-- view those tests read and write.
GRANT USAGE ON SCHEMA public TO service_role;

-- Read-only: order_items/order_item_stakes triggers look up pricing config
-- from these (SECURITY INVOKER, so they run as the calling role).
GRANT SELECT ON products TO service_role;
GRANT SELECT ON product_bundle_thresholds TO service_role;
GRANT SELECT ON product_price_tiers TO service_role;
GRANT SELECT ON syndicates TO service_role;
GRANT SELECT ON syndicate_members TO service_role;

GRANT SELECT, INSERT, UPDATE, DELETE ON orders TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON order_items TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON order_item_stakes TO service_role;
GRANT SELECT ON order_item_resolution TO service_role;

GRANT SELECT ON syndicate_member_profiles TO service_role;


-- authenticated is the demo app's own role, reached through PostgREST with a
-- signed-in user's JWT. Flat grants, no RLS: the accepted posture for one
-- seeded, trusted syndicate (SPEC.md's Architectural Decisions).
GRANT USAGE ON SCHEMA public TO authenticated;

GRANT SELECT ON products TO authenticated;
GRANT SELECT ON product_bundle_thresholds TO authenticated;
GRANT SELECT ON product_price_tiers TO authenticated;
GRANT SELECT ON syndicates TO authenticated;
GRANT SELECT ON syndicate_members TO authenticated;
GRANT SELECT ON syndicate_member_profiles TO authenticated;
GRANT SELECT ON order_item_resolution TO authenticated;

-- UPDATE on orders is the admin's close/execute action. UPDATE on order_items
-- is never a client write -- sync_order_item_quantity and sync_tiered_unit_price
-- are SECURITY INVOKER, so their own UPDATE order_items runs as whichever role
-- wrote the triggering stake.
GRANT SELECT, UPDATE ON orders TO authenticated;
GRANT SELECT, UPDATE ON order_items TO authenticated;

-- DELETE is stake withdrawal; INSERT/UPDATE are the two halves of the commit
-- upsert. trg_check_stake_order_is_open already confines all three to the open
-- window.
GRANT SELECT, INSERT, UPDATE, DELETE ON order_item_stakes TO authenticated;

-- stake_id is GENERATED BY DEFAULT AS IDENTITY, so inserts need its sequence.
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- Realtime carries only these two tables. Stake changes roll up into
-- order_items.quantity, so the app never subscribes to order_item_stakes.
ALTER PUBLICATION supabase_realtime ADD TABLE orders, order_items;
